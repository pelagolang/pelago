fn energy(x: &[f64; 5], y: &[f64; 5], z: &[f64; 5], vx: &[f64; 5], vy: &[f64; 5], vz: &[f64; 5], m: &[f64; 5]) -> f64 {
    let mut e = 0.0;
    for i in 0..5 {
        e += 0.5 * m[i] * (vx[i] * vx[i] + vy[i] * vy[i] + vz[i] * vz[i]);
        for j in i + 1..5 {
            let dx = x[i] - x[j];
            let dy = y[i] - y[j];
            let dz = z[i] - z[j];
            e -= m[i] * m[j] / (dx * dx + dy * dy + dz * dz).sqrt();
        }
    }
    e
}

fn main() {
    let pi = 3.141592653589793f64;
    let sm = 4.0 * pi * pi;
    let dpy = 365.24;
    let mut x = [0.0, 4.84143144246472090, 8.34336671824457987, 12.8943695621391310, 15.3796971148509165];
    let mut y = [0.0, -1.16032004402742839, 4.12479856412430479, -15.1111514016986312, -25.9193146099879641];
    let mut z = [0.0, -0.103622044471123109, -0.403523417114321381, -0.223307578892655734, 0.179258772950371181];
    let mut vx = [0.0, 0.00166007664274403694 * dpy, -0.00276742510726862411 * dpy, 0.00296460137564761618 * dpy, 0.00268067772490389322 * dpy];
    let mut vy = [0.0, 0.00769901118419740425 * dpy, 0.00499852801234917238 * dpy, 0.00237847173959480950 * dpy, 0.00162824170038242295 * dpy];
    let mut vz = [0.0, -0.0000690460016972063023 * dpy, 0.0000230417297573763929 * dpy, -0.0000296589568540237556 * dpy, -0.0000951592254519715870 * dpy];
    let m = [sm, 0.000954791938424326609 * sm, 0.000285885980666130812 * sm, 0.0000436624404335156298 * sm, 0.0000515138902046611451 * sm];
    let (mut px, mut py, mut pz) = (0.0, 0.0, 0.0);
    for i in 0..5 {
        px += vx[i] * m[i];
        py += vy[i] * m[i];
        pz += vz[i] * m[i];
    }
    vx[0] = -px / sm;
    vy[0] = -py / sm;
    vz[0] = -pz / sm;
    println!("{:.6}", energy(&x, &y, &z, &vx, &vy, &vz, &m));
    for _ in 0..200000 {
        for i in 0..5 {
            for j in i + 1..5 {
                let dx = x[i] - x[j];
                let dy = y[i] - y[j];
                let dz = z[i] - z[j];
                let d2 = dx * dx + dy * dy + dz * dz;
                let mag = 0.01 / (d2 * d2.sqrt());
                vx[i] -= dx * m[j] * mag;
                vy[i] -= dy * m[j] * mag;
                vz[i] -= dz * m[j] * mag;
                vx[j] += dx * m[i] * mag;
                vy[j] += dy * m[i] * mag;
                vz[j] += dz * m[i] * mag;
            }
        }
        for i in 0..5 {
            x[i] += 0.01 * vx[i];
            y[i] += 0.01 * vy[i];
            z[i] += 0.01 * vz[i];
        }
    }
    println!("{:.6}", energy(&x, &y, &z, &vx, &vy, &vz, &m));
}
