#!/usr/bin/env python3
"""Writes regex_corpus.pel and regex_corpus.out: random patterns and texts, with the expected lines from Python's `re`.

Run it once after changing the generator or the pattern language; the tests do not need Python.
    python3 gen_regex_corpus.py
"""
import random, re, sys

random.seed(20261110)
ALPHA = "abc1 \n_"
CASES = int(sys.argv[1]) if len(sys.argv) > 1 else 300

def atom(d):
    r = random.random()
    if d > 0 and r < 0.22:
        inner = alt(d - 1)
        kind = random.choice(["(", "(", "(?:", "(?<g>"])
        if kind == "(?<g>":
            return None  # names must be unique; handled below
        return kind + inner + ")"
    if r < 0.5:
        return random.choice("abc")
    if r < 0.58:
        return "."
    if r < 0.7:
        return random.choice(["[ab]", "[^a]", "[a-c]", "[^b-c1]", "\\d", "\\w", "\\s", "\\D", "\\W", "\\S"])
    if r < 0.74:
        return random.choice(["\\.", "\\_"])  # an escaped dot, an escaped underscore
    return random.choice("abc")

def quant(a):
    r = random.random()
    if r < 0.6:
        return a
    q = random.choice(["*", "+", "?", "{2}", "{1,2}", "{0,2}", "{2,}"])
    if random.random() < 0.3 and not q.endswith("}") or random.random() < 0.15:
        q += "?"
    return a + q

def cat(d):
    out = ""
    for _ in range(random.randint(1, 4)):
        a = atom(d)
        while a is None:
            a = atom(d)
        r = random.random()
        if r < 0.05:
            out += random.choice(["^", "$", "\\b", "\\B", "\\A", "\\z"])
        elif r < 0.09:
            out += random.choice(["(?=a)", "(?!b)", "(?=[ab])", "(?!\\d)", "(?=.b)", "(?!a|b)"])
        else:
            out += quant(a)
    return out

def alt(d):
    parts = [cat(d)]
    while random.random() < 0.25:
        parts.append(cat(d))
    return "|".join(parts)

def pattern():
    p = alt(2)
    r = random.random()
    if r < 0.12:
        p = "(?i)" + p
    elif r < 0.2:
        p = "(?s)" + p
    elif r < 0.28:
        p = "(?m)" + p
    elif r < 0.32:
        p = "(?im)" + p
    elif r < 0.36:
        p = "(?i:" + p + ")"
    return p

def text():
    return "".join(random.choice(ALPHA + "ABC") for _ in range(random.randint(0, 9)))

def to_python(p):
    return p.replace("\\z", "\\Z").replace("\\_", "_")

def pel(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'

def ours(p):
    return p.replace("\\_", "_")

lines, outs, pool = [], [], []
seen = set()
while len(lines) < CASES:
    p, t = pattern(), text()
    if (p, t) in seen:
        continue
    seen.add((p, t))
    if t == "" and "\\B" in p:
        continue  # Python before 3.14 never matches \B in an empty text; we follow Perl and Rust
    try:
        rx = re.compile(to_python(p))
    except re.error:
        continue
    hits = list(rx.finditer(t))
    spans = " ".join(f"{m.start()}-{m.end()}" for m in hits)
    repl, last = "", 0
    for m in hits:
        repl += t[last:m.start()] + "<" + m.group(0) + ">"
        last = m.end()
    repl += t[last:]
    pool.append((p, t, [m.group(0) for m in hits]))
    outs.append(f"{str(bool(hits)).lower()} {len(hits)} {spans} {repl}")
    lines.append(f"    t({pel(ours(p))}, {pel(t)}).or(1)")

head = '''/// Generated by gen_regex_corpus.py: random patterns and texts; the expected lines come from Python's `re`.
import std.regex

fn t(pattern: str, text: str) -> int ! parse_error {
    const re = regex.compile(pattern)?
    var spans = ""
    const hits = re.findAll(text)
    var i = 0
    while i < hits.len() {
        spans.pushStr!("#(hits[i].start)-#(hits[i].end) ")
        i += 1
    }
    print(re.isMatch(text), hits.len(), spans.trim(), re.replaceAll(text, "<$0>"))
    ok(0)
}

fn main() {
'''
open("regex_corpus.pel", "w").write(head + "\n".join(lines) + "\n}\n")
open("regex_corpus.out", "w").write("\n".join(outs) + "\n")

# The compile-time engine: the same patterns, wrapped in one named group and read by `@regex` into a struct.
ATTR_CASES = 16
decls, fns, calls, attr_outs = [], [], [], []
for k, (p, t, texts) in enumerate(pool[:ATTR_CASES]):
    n = f"c{k}"
    decls.append(f"@regex({pel(ours('(?<all>' + p + ')'))})\nstruct {n} {{\n    all: string\n}}\n")
    fns.append(f"""fn run{k}() {{
    const text = {pel(t)}
    const hits = {n}FindAll(text)
    var joined = ""
    var i = 0
    while i < hits.len() {{
        joined.pushStr!(hits[i].all)
        joined.pushStr!("|")
        i += 1
    }}
    print({n}IsMatch(text), hits.len(), joined)
}}
""")
    calls.append(f"    run{k}()")
    attr_outs.append(f"{str(bool(texts)).lower()} {len(texts)} " + "".join(m + "|" for m in texts))
open("regex_attr_corpus.pel", "w").write("/// Generated by gen_regex_corpus.py: the corpus patterns read by `@regex`; expected lines from Python's `re`.\n\n" + "\n".join(decls) + "\n" + "\n".join(fns) + "\nfn main() {\n" + "\n".join(calls) + "\n}\n")
open("regex_attr_corpus.out", "w").write("\n".join(attr_outs) + "\n")
