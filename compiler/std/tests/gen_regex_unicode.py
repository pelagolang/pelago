def main():
    if "--tables" in sys.argv or True:
        write_tables()
    out = []
    for pattern, text in CASES:
        real = text.replace("\\n", "\n")
        ms = list(re.finditer(expand_props(pattern), real))
        spans = " ".join("%d-%d" % (byte_offset(real, m.start()), byte_offset(real, m.end())) for m in ms)
        out.append("%s\t%s\ttrue %d %s" % (pattern, text, len(ms), spans))
    open("regex_unicode.corpus", "w").write("\n".join(out) + "\n")
    write_reference_test(out)

def pel_string(text):
    out = ""
    for ch in text:
        if ch == "\\":
            out += "\\\\"
        elif ch == '"':
            out += '\\"'
        elif ch == "\n":
            out += "\\n"
        else:
            out += ch
    return out

def write_reference_test(lines):
    """regex_unicode_ref.pel runs every corpus case through `regex.compile("(?u)...")` (the reference matcher); regex_unicode_ref.out is the corpus' expected column."""
    body = ["/// The reference matcher's Unicode mode (`(?u)` at run time): every case of regex_unicode.corpus, expected spans from Python.",
            "/// Generated by gen_regex_unicode.py.", "import std.regex", "",
            "fn show(pattern: str, text: str) -> int ! parse_error {",
            "    const re = regex.compile(\"(?u)#(pattern)\")?",
            "    const hits = re.findAll(text)",
            "    var spans = \"\"",
            "    var i = 0",
            "    while i < hits.len() {",
            "        spans.pushStr!(\"#(hits[i].start)-#(hits[i].end) \")",
            "        i += 1",
            "    }",
            "    print(true, hits.len(), \"#(spans.trim())\")",
            "    ok(0)",
            "}", "", "fn main() {"]
    expected = []
    for line in lines:
        pattern, text, exp = line.split("\t")
        body.append('    show("%s", "%s").or(1)' % (pel_string(pattern), pel_string(text.replace("\\n", "\n"))))
        expected.append(exp)
    body.append("}")
    open("regex_unicode_ref.pel", "w").write("\n".join(body) + "\n")
    open("regex_unicode_ref.out", "w").write("\n".join(expected) + "\n")

def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = False if 0xD800 <= cp <= 0xDFFF else pred(chr(cp))
        if ok and start is None:
            start = cp
        if not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out

def pel_table(fn, pairs, flat=True):
    """A table as a string of decimal numbers: a long list literal makes the IR optimiser very slow."""
    items = [str(n) for row in pairs for n in row]
    return "fn %s() -> [int] = ints(\"%s\")\n" % (fn, " ".join(items))

def write_pelago(names, runs):
    import _sre
    import re._casefix as casefix
    body = PEL_HEAD % (sys.version.split()[0], unicodedata.unidata_version)
    for name, pat in (("digitSet", r"\d"), ("wordSet", r"\w"), ("spaceSet", r"\s")):
        p = re.compile(pat)
        rs = ranges(lambda c: p.fullmatch(c) is not None)
        body += "pub " + pel_table(name, rs) + "\n"
    lower = [(cp, _sre.unicode_tolower(cp)) for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF and _sre.unicode_tolower(cp) != cp]
    body += pel_table("lowerTable", lower) + "\n"
    extra = [(k, v) for k, vs in sorted(casefix._EXTRA_CASES.items()) for v in vs]
    body += pel_table("extraTable", extra) + "\n"
    body += 'fn categoryNames() -> str = "%s"\n\n' % " ".join(names)
    body += pel_table("categoryRuns", [(lo, hi, names.index(c)) for lo, hi, c in runs])
    open("../regexunicode.pel", "w").write(body)

def write_tables():
    lines = [
        "//! Generated by `compiler/std/tests/gen_regex_unicode.py` (Python %s, Unicode %s): the sets Python's `re` uses for"
        % (sys.version.split()[0], unicodedata.unidata_version),
        "//! `\\d`, `\\w` and `\\s` on text. Do not edit by hand.",
        "",
    ]
    for name, pat in (("DIGITS", r"\d"), ("WORD", r"\w"), ("SPACE", r"\s")):
        p = re.compile(pat)
        rs = ranges(lambda c: p.fullmatch(c) is not None)
        lines.append("pub const %s: &[(u32, u32)] = &[" % name)
        for lo, hi in rs:
            lines.append("    (0x%X, 0x%X)," % (lo, hi))
        lines.append("];")
        lines.append("")
    import _sre
    import re._casefix as casefix
    lines.append("/// `(code point, its lower case)` for every code point Python's `re` lowers when it ignores case (`_sre.unicode_tolower`).")
    lines.append("pub const LOWER: &[(u32, u32)] = &[")
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        t = _sre.unicode_tolower(cp)
        if t != cp:
            lines.append("    (0x%X, 0x%X)," % (cp, t))
    lines.append("];")
    lines.append("")
    lines.append("/// `(lower case, other lower case it also matches)`: the extra equivalences of `re._casefix` (`s` and `\\u017f`, `\\u03c3` and `\\u03c2`, ...).")
    lines.append("pub const EXTRA: &[(u32, u32)] = &[")
    for k, vs in sorted(casefix._EXTRA_CASES.items()):
        for v in vs:
            lines.append("    (0x%X, 0x%X)," % (k, v))
    lines.append("];")
    lines.append("")
    names = []
    runs = []
    prev, start = None, 0
    for cp in range(0x110000):
        c = "Cs" if 0xD800 <= cp <= 0xDFFF else unicodedata.category(chr(cp))
        if c != prev:
            if prev is not None:
                runs.append((start, cp - 1, prev))
            prev, start = c, cp
    runs.append((start, 0x10FFFF, prev))
    names = sorted(set(c for _, _, c in runs))
    lines.append("/// The two-letter general categories, in the order the runs below index them.")
    lines.append("pub const CATEGORY_NAMES: &[&str] = &[%s];" % ", ".join('"%s"' % n for n in names))
    lines.append("")
    lines.append("/// Runs `(first, last, category index)` covering every code point (`unicodedata.category`).")
    lines.append("pub const CATEGORIES: &[(u32, u32, u8)] = &[")
    for lo, hi, c in runs:
        lines.append("    (0x%X, 0x%X, %d)," % (lo, hi, names.index(c)))
    lines.append("];")
    lines.append("")
    open("../../src/regexunicode_tables.rs", "w").write("\n".join(lines))
    write_pelago(names, runs)

main()
