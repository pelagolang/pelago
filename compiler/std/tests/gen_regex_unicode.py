#!/usr/bin/env python3
"""Writes regex_unicode.corpus and compiler/src/regexunicode_tables.rs from Python's `re` (Unicode mode is Python's default).

Run from this directory: python3 gen_regex_unicode.py

regex_unicode.corpus has one case per line: pattern TAB text TAB expected. In the text `\\n` stands for a newline.
The expected field is `true N spans` with spans in BYTE offsets of the UTF-8 text (the matcher works on bytes).
The test `regexgen_unicode_agrees_with_python` runs every pattern as `(?u)pattern`.
"""
import re
import sys
import unicodedata

CASES = [
    (r"\w+", "naïve café Straße ΑΒΓ дом 日本語 x_1"),
    (r".", "aé日😀"),
    (r"[^a-z]+", "abcéxyz日本q"),
    (r"[à-ÿ]+", "abcéàÿxz"),
    (r"[α-ω]+", "abc αβγ δ"),
    (r"\d+", "٣٤ 12 ٥ x"),
    (r"\s+", "a b c  d　e"),
    (r"é+", "éééa é"),
    (r"(?i)é+", "éÉé x"),
    (r"(?i)[à-ÿ]+", "ÀÉÎ àéî x"),
    (r"(?i)привет", "Привет ПРИВЕТ привет"),
    (r"[^\W\d]+", "ab12é٣x_"),
    (r"日本+", "日本本本 日"),
    (r"[日本]+", "日本語本"),
    (r"(?s).+", "a\\nb"),
    (r".+", "añb\\nçd"),
    (r"[é-ü]", "aéüz"),
    (r"x.?y", "xéy xy x😀y xaay"),
    (r"^.$", "😀"),
    (r"[😀-😂]+", "a😀😁😂😃"),
    (r"\w*é\w*", "café cafe élan"),
    (r"(?i)Σ", "σΣ"),
]

def literal(s):
    return s.replace("\n", "\\n")

def byte_offset(text, i):
    return len(text[:i].encode())

def main():
    if "--tables" in sys.argv or True:
        write_tables()
    out = []
    for pattern, text in CASES:
        real = text.replace("\\n", "\n")
        ms = list(re.finditer(pattern, real))
        spans = " ".join("%d-%d" % (byte_offset(real, m.start()), byte_offset(real, m.end())) for m in ms)
        out.append("%s\t%s\ttrue %d %s" % (pattern, text, len(ms), spans))
    open("regex_unicode.corpus", "w").write("\n".join(out) + "\n")

def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = False if 0xD800 <= cp <= 0xDFFF else pred(chr(cp))
        if ok and start is None:
            start = cp
        if not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out

def write_tables():
    lines = [
        "//! Generated by `compiler/std/tests/gen_regex_unicode.py` (Python %s, Unicode %s): the sets Python's `re` uses for"
        % (sys.version.split()[0], unicodedata.unidata_version),
        "//! `\\d`, `\\w` and `\\s` on text. Do not edit by hand.",
        "",
    ]
    for name, pat in (("DIGITS", r"\d"), ("WORD", r"\w"), ("SPACE", r"\s")):
        p = re.compile(pat)
        rs = ranges(lambda c: p.fullmatch(c) is not None)
        lines.append("pub const %s: &[(u32, u32)] = &[" % name)
        for lo, hi in rs:
            lines.append("    (0x%X, 0x%X)," % (lo, hi))
        lines.append("];")
        lines.append("")
    open("../../src/regexunicode_tables.rs", "w").write("\n".join(lines))

main()
